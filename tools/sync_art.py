"""Copy the local colour art to a MiSTer's t2o-wifi/art folder (non-destructive).

Sources, later ones win on a name clash (case-insensitive, like the daemon's lookup):
  1. library/color-gen/*.jpg          generated by tools/colorize_library.py
  2. library/local-extra/*.png|jpg    hand-curated; converted to a <=19 KB 240x240 JPEG

Only missing or changed files are copied (compared by MD5). Nothing is ever deleted on the
MiSTer, and the stock tty2oled folders (/media/fat/tty2oled/pics) are never touched; the
daemon reads art/ first and falls back to those grayscale pictures.

    python3 tools/sync_art.py --dry-run
    python3 tools/sync_art.py [--host mister.local] [--user root]
"""
import argparse
import hashlib
import io
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import colorize_library as cl  # noqa: E402  (export_jpeg/OUT/MAX_BYTES)

ROOT = Path(__file__).resolve().parent.parent
REMOTE_DIR = "/media/fat/t2o-wifi/art"


def local_art(tmp: Path) -> dict:
    """lower-case stem -> (file name, path)."""
    out = {}
    for p in sorted((ROOT / "library" / "color-gen").glob("*.jpg")):
        out[p.stem.lower()] = (p.name, p)
    extra = ROOT / "library" / "local-extra"
    for p in sorted(extra.glob("*")) if extra.is_dir() else []:
        if p.suffix.lower() not in (".png", ".jpg", ".jpeg"):
            continue
        dst = tmp / (p.stem + ".jpg")
        cl.export_jpeg(Image.open(p).convert("RGB"), dst)
        if p.stem.lower() in out:
            print(f"  {p.name}: hand-curated, overrides the generated {out[p.stem.lower()][0]}")
        out[p.stem.lower()] = (dst.name, dst)
    return out


def ssh(args, target, cmd):
    return subprocess.run(["ssh", "-o", "BatchMode=yes", target, cmd],
                          capture_output=True, text=True, check=True).stdout


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--host", default="mister.local")
    ap.add_argument("--user", default="root")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    target = f"{args.user}@{args.host}"

    with tempfile.TemporaryDirectory() as t:
        art = local_art(Path(t))
        remote = {}
        for line in ssh(args, target, f"mkdir -p {REMOTE_DIR} && cd {REMOTE_DIR} && md5sum * 2>/dev/null; true").splitlines():
            md5, _, name = line.partition("  ")
            if name:
                remote[name.lower()] = (name, md5)
        todo = []
        for key, (name, path) in sorted(art.items()):
            md5 = hashlib.md5(path.read_bytes()).hexdigest()
            r = remote.get(key + ".jpg")
            if r is None:
                todo.append((name, path, "new"))
            elif r[1] != md5:
                todo.append((name, path, "changed"))
        for name, _, why in todo:
            print(f"  {why:8} {name}")
        extra = sorted(n for k, (n, _) in remote.items() if k[:-4] not in art or not k.endswith(".jpg"))
        if extra:
            print(f"  note: {len(extra)} file(s) on the MiSTer not in the local set (left alone): {', '.join(extra[:8])}")
        print(f"{len(art)} local, {len(art) - len(todo)} already in sync, {len(todo)} to copy" + (" (dry run)" if args.dry_run else ""))
        if todo and not args.dry_run:
            subprocess.run(["scp", "-o", "BatchMode=yes", "-q", *[str(p) for _, p, _ in todo],
                            f"{target}:{REMOTE_DIR}/"], check=True)
            print("copied")


if __name__ == "__main__":
    main()
