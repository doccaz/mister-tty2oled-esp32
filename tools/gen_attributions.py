"""Write tools/ATTRIBUTIONS.md from the provenance fields in tools/themes.json.

Usage: python3 tools/gen_attributions.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "ATTRIBUTIONS.md"


def main() -> None:
    themes = json.loads((HERE / "themes.json").read_text())
    rows, other = [], []
    for core, t in sorted(themes.items(), key=lambda kv: kv[0].lower()):
        src = t.get("source", "")
        (rows if src.startswith("http") else other).append((core, t))

    out = [
        "# Colour art sources",
        "",
        "Generated by `tools/gen_attributions.py` from `tools/themes.json`; edit that file, not this one.",
        "",
        "The rendered JPEGs and the downloaded logo files are not in this repository "
        "(`library/color-gen/` and `library/color-src/` are gitignored, personal use only). "
        "Trademarks belong to their owners; \"public domain\" on Wikimedia Commons refers to "
        "copyright only.",
        "",
        "## Logos taken from Wikimedia Commons / the web",
        "",
        "| Core | Source | Licence | Local changes |",
        "|---|---|---|---|",
    ]
    for core, t in rows:
        esc = lambda s: str(s).replace("|", "\\|")
        out.append(f"| {core} | <{t['source']}> | {esc(t.get('license', ''))} | {esc(t.get('note', ''))} |")
    out += ["", "## Recoloured from the tty2oled picture packs, or supplied by the owner", "",
            "| Core | Source | Licence | Notes |", "|---|---|---|---|"]
    for core, t in other:
        esc = lambda s: str(s).replace("|", "\\|")
        out.append(f"| {core} | {esc(t.get('source', 'stock master'))} | {esc(t.get('license', 'third-party pack art, personal use only'))} | {esc(t.get('note', ''))} |")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.name}: {len(rows)} web sources, {len(other)} others")


if __name__ == "__main__":
    main()
